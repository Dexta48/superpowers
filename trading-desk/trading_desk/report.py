"""Render one run as markdown, and push it to a webhook."""
from __future__ import annotations

import requests

VERDICT = {
    "take": "TAKE",
    "take_reduced_size": "TAKE (reduced size)",
    "wait_for_confirmation": "WAIT",
    "reject": "REJECT",
}


def render(now: str, news: str, signals, reviews, risk: list[dict], errors: list[str], read=None) -> str:
    out = [f"# Trading desk — {now}", ""]
    if errors:
        out += ["> **Data problems:** " + "; ".join(errors), ""]
    out += ["## Signals", "", signals.market_context, ""]
    rev = {r.symbol: r for r in reviews.reviews}
    rk = {r["symbol"]: r for r in risk}
    for s in signals.signals:
        r, k = rev.get(s.symbol), rk.get(s.symbol, {})
        verdict = f" → risk desk: **{VERDICT[r.verdict]}** ({r.score_out_of_10}/10)" if r else ""
        out.append(f"### {s.symbol} — {s.direction.upper()}{verdict}")
        out.append("")
        if s.direction != "flat":
            rr = ", ".join(f"{x}R" for x in k.get("reward_to_risk_per_target", []))
            out += [
                f"- **Setup:** {s.setup} ({s.timeframe}, {s.confidence} confidence)",
                f"- **Entry** {s.entry} · **Stop** {s.stop} · **Targets** "
                + ", ".join(map(str, s.targets))
                + f" ({rr})",
                f"- **Risk:** {k.get('risk_points')} pts = ${k.get('risk_usd_per_contract')}"
                f"/contract as {k.get('sized_as')}; max {k.get('max_contracts_within_budget')} "
                f"contract(s) inside the ${k.get('risk_budget_usd')} budget",
                f"- **Invalidation:** {s.invalidation}",
            ]
            if k.get("structural_problems"):
                out.append("- **Malformed:** " + "; ".join(k["structural_problems"]))
        out += ["", s.rationale, ""]
        if r:
            out.append("**Risk desk**")
            out.append("")
            out += [f"- (+) {x}" for x in r.strengths] + [f"- (−) {x}" for x in r.weaknesses]
            out += [
                f"- **Risk:** {r.risk_assessment}",
                f"- **News:** {r.news_risk}",
                f"- **Adjust:** {r.suggested_adjustments}",
                "",
            ]
    out += ["## Combined exposure", "", reviews.portfolio_note, ""]
    if read:
        out += ["## Chart read", "", read.cross_market, ""]
        for a in read.analyses:
            out += [
                f"### {a.symbol} — {a.bias} ({a.bias_strength})",
                "",
                f"- **Trend:** daily {a.trend_daily} · 1h {a.trend_1h} · 15m {a.trend_15m}",
                f"- **Resistance:** {', '.join(map(str, a.key_resistance)) or '—'}",
                f"- **Support:** {', '.join(map(str, a.key_support)) or '—'}",
                f"- **Structure:** {a.structure}",
                f"- **Momentum:** {a.momentum}",
                f"- **Volatility:** {a.volatility}",
                f"- **Changes the view:** {a.what_would_change_it}",
                f"- **Data:** {a.data_quality}",
                "",
            ]
    out += ["## Upcoming news", "", news, ""]
    out.append("_Analysis only, generated by an AI model from delayed data. Not financial advice._")
    return "\n".join(out)


def push(webhook: str, markdown: str) -> None:
    """POST to a Discord-style webhook ({"content": ...}), split at its 2000-char limit."""
    chunk = ""
    for line in markdown.splitlines(keepends=True):
        while len(line) > 1900:
            chunk, line = chunk + line[: 1900 - len(chunk)], line[1900 - len(chunk) :]
            requests.post(webhook, json={"content": chunk}, timeout=15).raise_for_status()
            chunk = ""
        if len(chunk) + len(line) > 1900:
            requests.post(webhook, json={"content": chunk}, timeout=15).raise_for_status()
            chunk = ""
        chunk += line
    if chunk.strip():
        requests.post(webhook, json={"content": chunk}, timeout=15).raise_for_status()
